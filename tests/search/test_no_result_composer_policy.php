<?php
declare(strict_types=1);
$root = dirname(__DIR__, 2);
require_once $root . '/core/search/SearchCondition.php';
require_once $root . '/core/search/NoResultComposerPolicy.php';
require_once $root . '/core/search/ProductSearchPolicyRuntime.php';
require_once $root . '/core/search/ProductSearchVerificationTrace.php';
require_once $root . '/core/search/BatsSearchIntent.php';
require_once $root . '/core/search/BatsSearchIntentMapper.php';
require_once $root . '/core/search/ClarificationPolicy.php';
require_once $root . '/core/product_source/recommendation/ProductRecommendationBuilder.php';
require_once $root . '/core/product_source/recommendation/TravelConsultantPersonaRuntime.php';
require_once $root . '/core/intent/AiIntentUnderstandingRuntime.php';
require_once $root . '/core/tour_prompt_context_service.php';
$failures = 0;
function nr_assert(bool $cond, string $message): void { global $failures; if (!$cond) { ++$failures; fwrite(STDERR, "FAIL: {$message}\n"); } }
$noResultPolicy = new NoResultComposerPolicy();
$searchPolicy = new ProductSearchPolicyRuntime();
$builder = new ProductRecommendationBuilder($searchPolicy, $noResultPolicy);
$persona = new TravelConsultantPersonaRuntime();
$mapper = new BatsSearchIntentMapper();
$pilotSno = '5f99b8d665e8444d';
$ref = new DateTimeImmutable('2026-07-08', new DateTimeZone('Asia/Taipei'));
$case1Intent = ['destination' => '北海道', 'product_type' => '自由行', 'date_from' => '2026-11-01', 'date_to' => '2026-11-30'];
$case1Eval = $noResultPolicy->evaluateFromIntentArray($case1Intent);
nr_assert(($case1Eval['hard_constraints_complete'] ?? false) === true, 'case1: hard constraints complete');
$case1Summary = $builder->build([], $case1Intent, '北海道自由行，11月出發', ['policy' => 'product_type_strict', 'raw_count' => 0]);
nr_assert(($case1Summary['no_result_composer'] ?? false) === true, 'case1: no_result_composer');
nr_assert(($case1Summary['result_count'] ?? -1) === 0, 'case1: zero primary results');
$case1Reply = $persona->composeProductRecommendation($case1Summary);
nr_assert(strpos($case1Reply, '北海道') !== false, 'case1: reply mentions destination');
nr_assert(strpos($case1Reply, '自由行') !== false, 'case1: reply mentions product type');
nr_assert(strpos($case1Reply, '若您願意提供') === false, 'case1: must not ask for more info');
nr_assert(strpos($case1Reply, '* 日期') === false, 'case1: must not ask for date');
nr_assert(strpos($case1Reply, '* 出發地') === false, 'case1: must not ask for departure');
$case2Intent = BatsSearchIntent::empty('首爾自由行，7月出發')->with(['destination' => '首爾', 'product_type' => '自由行', 'date_from' => '2026-07-01', 'date_to' => '2026-07-31']);
$case2Condition = $mapper->toSearchCondition($case2Intent);
nr_assert($case2Condition !== null, 'case2: SearchCondition built');
$mockSearchClient = new TourSearchApiClient('https://example.test/tour/search', 5, static function (): array {
    $body = json_encode(['success' => true, 'pagination' => ['total' => 1], 'items' => [['title' => '首爾7月自由行五日', 'tourDate' => '2026-07-10', 'price' => 31800]], 'search_url' => 'https://example.test/search', 'error' => null], JSON_UNESCAPED_UNICODE);
    return ['ok' => true, 'http_status' => 200, 'body' => $body !== false ? $body : '', 'transport_error' => null];
});
$service = new TourPromptContextService();
$case2Exec = $service->buildTourContextResult(['userText' => '首爾自由行，7月出發', 'sno' => $pilotSno, 'featureEnabled' => true, 'referenceDate' => $ref, 'searchClient' => $mockSearchClient, 'authoritativeIntent' => $case2Intent]);
nr_assert(count($case2Exec->getSearchResults()) > 0, 'case2: runtime must not return zero when API has FIT');
$trace = ProductSearchVerificationTrace::build($case2Exec->getIntent(), $case2Condition, $pilotSno, count($case2Exec->getSearchResults()), $case2Exec->getSearchPolicyMeta());
nr_assert(($trace['source_keyword_query'] ?? '') === '首爾 自由行', 'case2: source_keyword_query');
nr_assert(strpos((string) ($trace['final_search_url'] ?? ''), 'keyword=') !== false, 'case2: final url has keyword');
nr_assert(strpos((string) ($trace['final_search_url'] ?? ''), 'dateFrom=2026-07-01') !== false, 'case2: final url dateFrom');
nr_assert(strpos((string) ($trace['final_search_url'] ?? ''), 'dateTo=2026-07-31') !== false, 'case2: final url dateTo');
nr_assert($case2Exec->getIntent()->getProductType() === '自由行', 'case2: product_type preserved in runtime');
$runtimeEntity = $case2Exec->getIntent()->toArray();
nr_assert(!array_key_exists('keyword', $runtimeEntity), 'case2: runtime keyword not polluted');
$case3Items = [['title' => '京都一般行程'], ['title' => '京都鐵道溫泉賞楓六日'], ['title' => '京都美食團']];
$case3 = SearchCondition::empty('京都鐵道溫泉賞楓，11月')->with(['destination' => '京都', 'keyword' => '鐵道溫泉賞楓', 'date_from' => '2026-11-01', 'date_to' => '2026-11-30']);
$case3Policy = $searchPolicy->apply($case3, $case3Items);
nr_assert(($case3Policy['policy'] ?? '') === 'keyword_preference', 'case3: keyword preference');
nr_assert(count($case3Policy['primary_results']) === 3, 'case3: no strict filter');
nr_assert(strpos((string) $case3Policy['primary_results'][0]['title'], '鐵道') !== false, 'case3: keyword ranked first');
$runtime = AiIntentUnderstandingRuntime::createForTesting();
$case4 = $runtime->understand('北海道', ['conversation_id' => $pilotSno . ':line:U-nr4', 'tenant_sno' => $pilotSno, 'now' => $ref, 'reference_date' => $ref]);
nr_assert($case4->isClarificationRequired() === true, 'case4: date clarification required');
nr_assert(($case4->getEntity()['destination'] ?? '') === '北海道', 'case4: destination preserved');
$case5Intent = BatsSearchIntent::empty('我想去賞楓');
$case5Applied = (new ClarificationPolicy())->apply($case5Intent);
nr_assert($case5Applied->isClarificationRequired() === true, 'case5: destination clarification');
nr_assert($case5Applied->getClarificationReason() === ClarificationPolicy::REASON_DESTINATION_UNKNOWN, 'case5: destination_unknown');
if ($failures === 0) { echo "ALL PASS test_no_result_composer_policy\n"; exit(0); }
fwrite(STDERR, "{$failures} FAILURE(S) in test_no_result_composer_policy\n"); exit(1);